/**
 * 供应商画像表（类型定义 + 真源导出）
 *
 * 唯一真源数据文件：`ClawX/src/data/迪拜8仓供应商条件绩效画像表_v5_2026-01_08.json`
 * （由业务侧产出，本文件只做类型标注与转发；换版本时替换 JSON 并改下面这一行 import 即可）。
 *
 * 派生链路（`pnpm --filter weights-guard gen:portrait`，脚本 gen-portrait-md.mjs 直接读上述 JSON）：
 *   ① `~/.openclaw/workspace-po/Suppliers.md`      —— agent 只读的权威 markdown 表
 *   ② `~/.openclaw/workspace-po/供应商画像.json`    —— 画像看板运行时 readTextFile 读取
 *   ③ `ClawX/shared/po-supplier-portrait.json`     —— electron 预置种子（必须放 shared/）
 *
 * 重要：字段命名与上游 TypeBox schema（画像行/仓库画像表/多仓画像表）保持一致，请勿随意重命名。
 * 行的唯一键 = 供应商 × 工种 × 班次 × 用工性质 × 技能等级 × 量档（所属仓由外层对象给出）。
 */
import 画像真源 from './迪拜8仓供应商条件绩效画像表_v5_2026-01_08.json';

/** 班次枚举；「未知」表示该组合历史数据未区分班次。 */
export type 班次 = '白班' | '跨夜' | '夜班' | '未知';

/**
 * 用工性质。真源为业务全称（如「劳务外包-O序列-综合排班临时工」），
 * 口径可能扩充，故不收敛为字面量联合。
 */
export type 用工性质 = string;

/** 档级枚举：①细=细网格桶，②粗=粗桶，④基准=本仓全体基准回落行。 */
export type 档级 = '①细' | '②粗' | '④基准';

/** 技能等级：高 / 中 / 低。 */
export type 技能等级 = '高' | '中' | '低';

/** 置信度：由后验区间宽度映射而来的离散等级；基准行为极低。 */
export type 置信度 = '高' | '中' | '低' | '极低';

/** 画像表单行。 */
export interface 画像行 {
  /** 供应商名称；「全体基准」为本仓回落兜底行。 */
  供应商: string;
  工种: string;
  班次: 班次;
  用工性质: 用工性质;
  技能等级: 技能等级;
  档级: 档级;
  /** 该行结论的可信等级；基准兜底行为「极低」。 */
  置信度: 置信度;
  需求量下限: number;
  需求量上限: number;
  /** 该组合量档的协议均价，单位：美元/(人·天)；无报价数据时为 null。 */
  价格: number | null;
  /** 实际到岗/需求人数。 */
  供给率: number;
  /** 下单到到岗天数（time to fill）。 */
  到岗天数: number;
  考勤率: number;
  /** 三个月内离职人数/实际到岗人数。 */
  离职率: number;
  /** 每人每天完成工作量（件/人/天）。 */
  人效: number;
  /** 历史上该组合达到过的最大供给人数，是供应能力上限的经验参考。 */
  历史最大供给量: number;
  样本人数: number;
}

/** 单个物流仓的画像表。 */
export interface 仓库画像表 {
  /** 物流仓名称，如 迪拜定制8号仓。 */
  物流仓: string;
  /** [下限, 上限]，超出即走回落。 */
  覆盖范围: [number, number];
  时限档: { 下限: number; 上限: number; 说明?: string };
  行: 画像行[];
}

/** 多仓画像表（顶层）。 */
export interface 多仓画像表 {
  画像版本: string;
  仓库: 仓库画像表[];
}

/** 画像表真源（JSON 字面量经类型收敛后导出）。 */
export const 供应商画像表 = 画像真源 as unknown as 多仓画像表;

/**
 * 物流仓行政层级项（洲际 → 片区 → 物流仓）。
 *
 * 真源画像 JSON 只有 `物流仓` 一个字段，没有洲际/片区维度，且真源仓名（如「迪拜定制8号仓」）
 * 与业务对外展示名（如「阿联酋迪拜定制8号仓」）不一致。为避免改真源 schema 触发
 * gen:portrait 三处产物连带刷新，层级信息放在前端这张映射表里：
 * - `真源物流仓` 用于和画像 JSON 里的 `仓库[].物流仓` 做匹配；
 * - `物流仓` 仅用于看板 UI 展示与筛选。
 *
 * 新增仓时在此追加一行即可；未登记的仓会在区域健康看板里归入「未分区」，不会丢数据。
 */
export interface 仓库层级项 {
  洲际: string;
  片区: string;
  /** 看板展示名。 */
  物流仓: string;
  /** 画像 JSON 中的真实仓名。 */
  真源物流仓: string;
}

/** 未登记层级的仓在筛选器里的归属标签。 */
export const 未分区标签 = '未分区';

