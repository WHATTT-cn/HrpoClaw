/**
 * 供应商画像表（硬编码测试数据）
 *
 * 数据来源：doc/conditional_score_table.ts 中的「测试多仓画像表」。
 * 这里以纯 TS 字面量形式落在 web 侧，供 PO agent 对话窗口左侧的「供应商画像看板」直接 import 渲染。
 *
 * 重要：后续工具（如 weights-guard / experience-capture 相关能力）也可能需要查找此数据表，
 * 因此保持字段命名与上游 TypeBox schema（画像行/仓库画像表/多仓画像表）严格一致，
 * 便于跨端复用与查表。请勿随意重命名字段。
 *
 * 行的唯一键 = 供应商 × 工种 × 班次 × 用工性质 × 量档（所属仓由外层对象给出）。
 * 每行数值 = 该组合下的历史均值，互不相同。
 */

/** 班次枚举。 */
export type 班次 = '白班' | '夜班';

/** 用工性质枚举。 */
export type 用工性质 =
  | '海外日常临时工'
  | '综合排班临时工'
  | '日结临时工'
  | '非全日制临时工';

/** 档级枚举：①细=细网格桶，②粗=粗桶，④基准=本仓全体基准回落行。 */
export type 档级 = '①细' | '②粗' | '④基准';

/** 画像表单行。 */
export interface 画像行 {
  /** 供应商名称；「全体基准」为本仓回落兜底行。 */
  供应商: string;
  工种: string;
  班次: 班次;
  用工性质: 用工性质;
  档级: 档级;
  需求量下限: number;
  需求量上限: number;
  /** 该组合量档的协议均价，单位：美元/(人·天)。 */
  价格: number;
  /** 实际到岗/需求人数。 */
  供给率: number;
  到岗天数: number;
  考勤率: number;
  /** 三个月内离职人数/实际到岗人数。 */
  离职率: number;
  /** 每人每天完成工作量（件/人/天）。 */
  人效: number;
  /** 后验区间宽度，映射置信度：<5高/5-8中/>8低/基准=极低。 */
  区间宽度pp: number;
  样本人数: number;
  /** 变点扫描识别的临界供应量；无则 null。 */
  临界量: number | null;
}

/** 单个物流仓的画像表。 */
export interface 仓库画像表 {
  /** 物流仓名称，如 A物流仓。 */
  物流仓: string;
  /** [下限, 上限]，超出即走回落。 */
  覆盖范围: [number, number];
  时限档: { 下限: number; 上限: number; 说明?: string };
  行: 画像行[];
}

/** 多仓画像表（顶层）。 */
export interface 多仓画像表 {
  画像版本: string;
  仓库: 仓库画像表[];
}

